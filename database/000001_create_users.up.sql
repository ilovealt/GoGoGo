BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(100) NOT NULL DEFAULT '',

    role VARCHAR(32) NOT NULL DEFAULT 'viewer',
    status SMALLINT NOT NULL DEFAULT 1,
    token_version INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_users_status
        CHECK (status IN (0, 1)),

    CONSTRAINT ck_users_role
        CHECK (role IN ('admin', 'operator', 'viewer')),

    CONSTRAINT ck_users_username_lower
        CHECK (username = lower(username))
);

-- 用户名不区分大小写：应用层统一 trim + lower 后再写入/查询
CREATE UNIQUE INDEX uk_users_username
    ON users (lower(username));

COMMENT ON TABLE users IS '系统用户表';
COMMENT ON COLUMN users.username IS '登录账号（统一转小写存储）';
COMMENT ON COLUMN users.password_hash IS '密码哈希';
COMMENT ON COLUMN users.role IS '角色：admin管理员，operator操作员，viewer只读';
COMMENT ON COLUMN users.status IS '状态：0禁用，1启用';
COMMENT ON COLUMN users.token_version IS '令牌版本，递增后使已签发的Access Token失效';

COMMIT;
