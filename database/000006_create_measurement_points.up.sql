BEGIN;

CREATE TABLE measurement_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    equipment_id BIGINT,

    code VARCHAR(128) NOT NULL,
    name VARCHAR(128) NOT NULL,
    description TEXT,

    point_type VARCHAR(32) NOT NULL,
    value_type SMALLINT NOT NULL DEFAULT 1,

    unit VARCHAR(32),
    precision SMALLINT NOT NULL DEFAULT 2,

    min_value DOUBLE PRECISION,
    max_value DOUBLE PRECISION,

    deadband DOUBLE PRECISION NOT NULL DEFAULT 0,

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    status SMALLINT NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_measurement_points_equipment
        FOREIGN KEY (equipment_id)
        REFERENCES equipments(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_measurement_points_value_type
        CHECK (value_type IN (1, 2, 3)),

    CONSTRAINT ck_measurement_points_status
        CHECK (status IN (0, 1)),

    CONSTRAINT ck_measurement_points_precision
        CHECK (precision BETWEEN 0 AND 15),

    CONSTRAINT ck_measurement_points_range
        CHECK (
            min_value IS NULL
            OR max_value IS NULL
            OR min_value <= max_value
        ),

    CONSTRAINT ck_measurement_points_deadband
        CHECK (deadband >= 0),

    CONSTRAINT ck_measurement_points_metadata
        CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE UNIQUE INDEX uk_measurement_points_code
    ON measurement_points (code)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_measurement_points_equipment_id
    ON measurement_points (equipment_id);

CREATE INDEX idx_measurement_points_type
    ON measurement_points (point_type);

CREATE INDEX idx_measurement_points_status
    ON measurement_points (status)
    WHERE deleted_at IS NULL;

COMMENT ON TABLE measurement_points IS '工业测点表';
COMMENT ON COLUMN measurement_points.code IS '全局唯一测点编码';
COMMENT ON COLUMN measurement_points.point_type IS '测点类型：temperature、pressure、flow、level等';
COMMENT ON COLUMN measurement_points.value_type IS '数据类型：1数值，2字符串，3布尔';
COMMENT ON COLUMN measurement_points.unit IS '工程单位';
COMMENT ON COLUMN measurement_points.precision IS '显示精度';
COMMENT ON COLUMN measurement_points.deadband IS '数据变化死区';
COMMENT ON COLUMN measurement_points.metadata IS '测点扩展属性JSON';
COMMENT ON COLUMN measurement_points.deleted_at IS '软删除时间';

COMMIT;
