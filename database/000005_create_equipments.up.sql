BEGIN;

CREATE TABLE equipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    area_id BIGINT NOT NULL,

    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,

    equipment_type VARCHAR(64),
    description TEXT,

    status SMALLINT NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_equipments_area
        FOREIGN KEY (area_id)
        REFERENCES areas(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_equipments_status
        CHECK (status IN (0, 1))
);

-- 使用部分唯一索引，软删除后允许重新使用同一区域下的设备编码
CREATE UNIQUE INDEX uk_equipments_area_code
    ON equipments (area_id, code)
    WHERE deleted_at IS NULL;

-- 改为部分唯一索引后，该索引不再被唯一索引覆盖，外键检查仍然需要
CREATE INDEX idx_equipments_area_id
    ON equipments (area_id);

CREATE INDEX idx_equipments_deleted_at
    ON equipments (deleted_at);

COMMENT ON TABLE equipments IS '工业设备表';
COMMENT ON COLUMN equipments.area_id IS '所属工艺区域ID';
COMMENT ON COLUMN equipments.code IS '设备编码';
COMMENT ON COLUMN equipments.equipment_type IS '设备类型';
COMMENT ON COLUMN equipments.status IS '状态：0禁用，1启用';
COMMENT ON COLUMN equipments.deleted_at IS '软删除时间';

COMMIT;
