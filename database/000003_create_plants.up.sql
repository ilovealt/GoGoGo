BEGIN;

CREATE TABLE plants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    description TEXT,
    timezone VARCHAR(64) NOT NULL DEFAULT 'UTC',

    status SMALLINT NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uk_plants_code UNIQUE (code),

    CONSTRAINT ck_plants_status
        CHECK (status IN (0, 1))
);

COMMENT ON TABLE plants IS '工厂表';
COMMENT ON COLUMN plants.code IS '工厂编码';
COMMENT ON COLUMN plants.name IS '工厂名称';
COMMENT ON COLUMN plants.timezone IS '工厂时区，用于按本地日聚合报表；数据仍按UTC存储';
COMMENT ON COLUMN plants.status IS '状态：0禁用，1启用';

COMMIT;
