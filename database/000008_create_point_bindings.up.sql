BEGIN;

CREATE TABLE point_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    point_id BIGINT NOT NULL,
    source_id BIGINT NOT NULL,

    address_config JSONB NOT NULL DEFAULT '{}'::jsonb,
    conversion_config JSONB NOT NULL DEFAULT '{}'::jsonb,

    enabled BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_point_bindings_point
        FOREIGN KEY (point_id)
        REFERENCES measurement_points(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_point_bindings_source
        FOREIGN KEY (source_id)
        REFERENCES data_sources(id)
        ON DELETE CASCADE,

    CONSTRAINT uk_point_bindings_point_source
        UNIQUE (point_id, source_id),

    CONSTRAINT ck_point_bindings_address
        CHECK (jsonb_typeof(address_config) = 'object'),

    CONSTRAINT ck_point_bindings_conversion
        CHECK (jsonb_typeof(conversion_config) = 'object')
);

CREATE INDEX idx_point_bindings_source_id
    ON point_bindings (source_id);

CREATE INDEX idx_point_bindings_enabled
    ON point_bindings (enabled)
    WHERE enabled = TRUE;

COMMENT ON TABLE point_bindings IS '测点与通讯数据源绑定表';
COMMENT ON COLUMN point_bindings.point_id IS '测点ID';
COMMENT ON COLUMN point_bindings.source_id IS '数据源ID';
COMMENT ON COLUMN point_bindings.address_config IS '通讯地址配置JSON';
COMMENT ON COLUMN point_bindings.conversion_config IS '数据转换配置JSON';
COMMENT ON COLUMN point_bindings.enabled IS '是否启用';

COMMIT;
