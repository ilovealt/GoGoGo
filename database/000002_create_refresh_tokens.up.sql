BEGIN;

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    -- 应用层使用字符串生成/比较 family_id，这里用 VARCHAR 便于 GORM/pgx 映射
    family_id VARCHAR(64) NOT NULL,
    replaced_by_id BIGINT,

    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    user_agent TEXT,
    ip VARCHAR(64),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_refresh_tokens_replaced_by
        FOREIGN KEY (replaced_by_id)
        REFERENCES refresh_tokens(id)
        ON DELETE SET NULL,

    CONSTRAINT uk_refresh_tokens_hash
        UNIQUE (token_hash)
);

-- 用户删除时 ON DELETE CASCADE 需要全量 user_id 索引
CREATE INDEX idx_refresh_tokens_user_id
    ON refresh_tokens (user_id);

CREATE INDEX idx_refresh_tokens_family_id
    ON refresh_tokens (family_id);

CREATE INDEX idx_refresh_tokens_replaced_by_id
    ON refresh_tokens (replaced_by_id);

CREATE INDEX idx_refresh_tokens_expires_at
    ON refresh_tokens (expires_at);

COMMENT ON TABLE refresh_tokens IS '刷新令牌表';
COMMENT ON COLUMN refresh_tokens.token_hash IS 'Refresh Token 的 SHA-256 十六进制哈希';
COMMENT ON COLUMN refresh_tokens.family_id IS '轮换族ID，用于检测重放';
COMMENT ON COLUMN refresh_tokens.replaced_by_id IS '轮换后签发的新令牌ID';
COMMENT ON COLUMN refresh_tokens.revoked_at IS '撤销时间，NULL表示有效';
COMMENT ON COLUMN refresh_tokens.expires_at IS '过期时间';

COMMIT;
