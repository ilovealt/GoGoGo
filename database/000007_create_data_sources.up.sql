BEGIN;

CREATE TABLE data_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(128) NOT NULL,
    protocol VARCHAR(32) NOT NULL,
    endpoint TEXT NOT NULL,

    config JSONB NOT NULL DEFAULT '{}'::jsonb,

    status SMALLINT NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uk_data_sources_name
        UNIQUE (name),

    CONSTRAINT ck_data_sources_protocol
        CHECK (protocol IN ('opcua', 'modbus_tcp', 'mqtt')),

    CONSTRAINT ck_data_sources_status
        CHECK (status IN (0, 1)),

    CONSTRAINT ck_data_sources_config
        CHECK (jsonb_typeof(config) = 'object')
);

CREATE INDEX idx_data_sources_protocol
    ON data_sources (protocol);

CREATE INDEX idx_data_sources_status
    ON data_sources (status);

COMMENT ON TABLE data_sources IS '工业数据采集数据源表';
COMMENT ON COLUMN data_sources.name IS '数据源名称';
COMMENT ON COLUMN data_sources.protocol IS '通讯协议：opcua、modbus_tcp、mqtt';
COMMENT ON COLUMN data_sources.endpoint IS '通讯服务地址';
COMMENT ON COLUMN data_sources.config IS '协议连接配置JSON';
COMMENT ON COLUMN data_sources.status IS '状态：0禁用，1启用';

COMMIT;
