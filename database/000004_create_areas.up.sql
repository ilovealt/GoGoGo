BEGIN;

CREATE TABLE areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    plant_id BIGINT NOT NULL,
    parent_id BIGINT,

    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    description TEXT,

    status SMALLINT NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_areas_plant
        FOREIGN KEY (plant_id)
        REFERENCES plants(id)
        ON DELETE RESTRICT,

    -- 复合唯一键用于下面的复合外键，保证父子区域属于同一工厂
    CONSTRAINT uk_areas_id_plant
        UNIQUE (id, plant_id),

    CONSTRAINT fk_areas_parent
        FOREIGN KEY (parent_id, plant_id)
        REFERENCES areas(id, plant_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_areas_not_self_parent
        CHECK (parent_id IS NULL OR parent_id <> id),

    CONSTRAINT ck_areas_status
        CHECK (status IN (0, 1)),

    CONSTRAINT uk_areas_plant_code
        UNIQUE (plant_id, code)
);

CREATE INDEX idx_areas_parent_id
    ON areas (parent_id);

COMMENT ON TABLE areas IS '工艺区域表';
COMMENT ON COLUMN areas.plant_id IS '所属工厂ID';
COMMENT ON COLUMN areas.parent_id IS '上级区域ID，必须与当前区域属于同一工厂';
COMMENT ON COLUMN areas.code IS '区域编码';
COMMENT ON COLUMN areas.status IS '状态：0禁用，1启用';

COMMIT;
